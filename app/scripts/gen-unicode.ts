// Generates app/src/core/pyunicode.ts from the frozen Python Unicode tables.
// Run: node app/scripts/gen-unicode.ts
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = new URL("../../", import.meta.url);
const source = JSON.parse(
  readFileSync(new URL("tests/fixtures/synthetic/golden/unicode.json", root), "utf8"),
) as {
  python: string;
  unidata_version: string;
  space: number[];
  casefold: [number, string][];
  word_ranges: [number, number][];
};

// Casefold pairs are stored as "code point, folded string" with the folded value
// encoded as code points to keep the generated file ASCII-only.
const fold = source.casefold
  .map(([cp, folded]) => `[${cp},[${Array.from(folded, (c) => c.codePointAt(0)).join(",")}]]`)
  .join(",");
const words = source.word_ranges.flat().join(",");
const output = `// Generated by app/scripts/gen-unicode.ts from Python ${source.python}
// (Unicode ${source.unidata_version}). Do not edit by hand.
export const PY_UNICODE_VERSION = ${JSON.stringify(source.unidata_version)};
/** Code points for which Python's str.isspace() is true. */
export const SPACE_CODES: readonly number[] = [${source.space.join(",")}];
/** Code points whose Python casefold() differs from the character itself. */
export const CASEFOLD_CODES: readonly (readonly [number, readonly number[]])[] = [${fold}];
/** Inclusive [start, end] pairs matched by Python's Unicode \\w. */
export const WORD_RANGES: readonly number[] = [${words}];
`;
const target = fileURLToPath(new URL("app/src/core/pyunicode.ts", root));
writeFileSync(target, output);
console.log(`wrote ${target}`);
